            ELSE NULL::date
        END AS event_date,
    gb.confirmation_email_sent_at IS NOT NULL AS confirmation_sent,
    (EXISTS ( SELECT 1 FROM traveler_records tr WHERE tr.booking_id = gb.id)) AS precheckin_done,
    ( SELECT count(*) FROM traveler_records tr WHERE tr.booking_id = gb.id) AS traveler_count,
    (EXISTS ( SELECT 1 FROM access_codes ac WHERE ac.booking_id = gb.id AND (ac.status = ANY (ARRAY['active'::text, 'pending_provision'::text])))) AS has_access_code
   FROM guest_bookings gb
     JOIN apartments a ON a.id = gb.apartment_id
  WHERE (gb.status = ANY (ARRAY['confirmed'::text, 'completed'::text]))
    AND (gb.check_in >= CURRENT_DATE AND gb.check_in <= (CURRENT_DATE + 14) OR gb.check_out >= CURRENT_DATE AND gb.check_out <= (CURRENT_DATE + 14));

CREATE OR REPLACE VIEW public.v_customers_360 WITH (security_invoker=true) AS
 WITH base AS (
         SELECT lower(TRIM(BOTH FROM gb.guest_email)) AS email,
            max(gb.guest_name) AS last_name_from_bookings,
            max(gb.guest_phone) AS last_phone_from_bookings,
            count(*) FILTER (WHERE gb.status = ANY (ARRAY['confirmed'::text, 'completed'::text])) AS total_stays,
            count(*) FILTER (WHERE gb.status = 'cancelled'::text) AS total_cancelled,
            COALESCE(sum(gb.total_price) FILTER (WHERE gb.status = ANY (ARRAY['confirmed'::text, 'completed'::text])), 0::numeric) AS lifetime_value,
            min(gb.check_in) FILTER (WHERE gb.status = ANY (ARRAY['confirmed'::text, 'completed'::text])) AS first_stay,
            max(gb.check_out) FILTER (WHERE gb.status = ANY (ARRAY['confirmed'::text, 'completed'::text])) AS last_stay,
            COALESCE(sum(gb.check_out - gb.check_in) FILTER (WHERE gb.status = ANY (ARRAY['confirmed'::text, 'completed'::text])), 0::bigint) AS total_nights
           FROM guest_bookings gb
          WHERE gb.guest_email IS NOT NULL AND gb.guest_email <> ''::text
          GROUP BY 1
        )
 SELECT b.email,
    COALESCE(c.canonical_name, b.last_name_from_bookings) AS last_name,
    COALESCE(c.phone, b.last_phone_from_bookings) AS last_phone,
    c.tags, c.preferences, c.preferred_language, c.nationality,
    b.total_stays, b.total_cancelled, b.lifetime_value,
    b.first_stay, b.last_stay, b.total_nights,
    fav.name AS favorite_apartment,
    note.body AS last_note, note.is_warning AS last_note_is_warning, note.created_at AS last_note_at,
    nc.notes_count, nc.warnings_count, r.avg_rating
   FROM base b
     LEFT JOIN customers c ON c.email = b.email
     LEFT JOIN LATERAL ( SELECT a.name FROM guest_bookings gb2 JOIN apartments a ON a.id = gb2.apartment_id
          WHERE lower(TRIM(BOTH FROM gb2.guest_email)) = b.email AND (gb2.status = ANY (ARRAY['confirmed'::text, 'completed'::text]))
          GROUP BY a.name ORDER BY (count(*)) DESC LIMIT 1) fav ON true
     LEFT JOIN LATERAL ( SELECT cn.body, cn.is_warning, cn.created_at FROM customer_notes cn
          WHERE cn.customer_email = b.email ORDER BY cn.created_at DESC LIMIT 1) note ON true
     LEFT JOIN LATERAL ( SELECT count(*) AS notes_count, count(*) FILTER (WHERE customer_notes.is_warning) AS warnings_count
           FROM customer_notes WHERE customer_notes.customer_email = b.email) nc ON true
     LEFT JOIN LATERAL ( SELECT round(avg(rv.rating), 1) AS avg_rating FROM reviews rv JOIN profiles p ON p.id = rv.profile_id
          WHERE lower(TRIM(BOTH FROM p.email)) = b.email) r ON true;


