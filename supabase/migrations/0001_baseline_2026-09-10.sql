CREATE OR REPLACE FUNCTION public.issue_invoice(p_booking_id bigint, p_receptor_nif text DEFAULT NULL::text, p_receptor_nombre text DEFAULT NULL::text, p_receptor_direccion text DEFAULT NULL::text, p_receptor_email text DEFAULT NULL::text)
 RETURNS TABLE(invoice_id uuid, serie text, numero bigint, total numeric)
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_existing_id uuid;
    v_existing_serie text;
    v_existing_numero bigint;
    v_existing_total numeric;
    v_year int := EXTRACT(YEAR FROM current_date)::int;
    v_serie text := 'A' || v_year::text;
    v_numero bigint;
    v_booking record;
    v_concepto text;
    v_total numeric;
    v_base numeric;
    v_cuota numeric;
    v_tipo_iva numeric := 10.00;
    v_hash_previo text;
    v_invoice_id uuid;
BEGIN
    -- Idempotencia
    SELECT id, serie, numero, total
    INTO v_existing_id, v_existing_serie, v_existing_numero, v_existing_total
    FROM public.invoices
    WHERE booking_id = p_booking_id AND tipo != 'rectificativa'
    LIMIT 1;
    IF v_existing_id IS NOT NULL THEN
        RETURN QUERY SELECT v_existing_id, v_existing_serie, v_existing_numero, v_existing_total;
        RETURN;
    END IF;

    -- Cargar booking
    SELECT gb.id, gb.booking_code, gb.check_in, gb.check_out, gb.total_price,
           gb.guest_name, gb.guest_email, gb.pax_count, a.name AS apt_name
    INTO v_booking
    FROM public.guest_bookings gb
    JOIN public.apartments a ON a.id = gb.apartment_id
    WHERE gb.id = p_booking_id;

    IF v_booking IS NULL THEN
        RAISE EXCEPTION 'booking_not_found' USING ERRCODE = '22023';
    END IF;

    v_concepto := format('Estancia en %s del %s al %s (%s noches, %s personas)',
        v_booking.apt_name, v_booking.check_in, v_booking.check_out,
        (v_booking.check_out - v_booking.check_in), v_booking.pax_count);

    v_total := v_booking.total_price;
    v_base := ROUND(v_total / (1 + v_tipo_iva / 100), 2);
    v_cuota := v_total - v_base;

    -- Numeracion correlativa por serie del ano
    SELECT COALESCE(MAX(numero), 0) + 1 INTO v_numero
    FROM public.invoices WHERE serie = v_serie;

    -- Hash previo (cadena Verifactu)
    SELECT verifactu_hash INTO v_hash_previo
    FROM public.invoices
    WHERE serie = v_serie AND numero = v_numero - 1;

    INSERT INTO public.invoices (
        booking_id, serie, numero, fecha_emision, tipo,
        receptor_nif, receptor_nombre, receptor_direccion, receptor_email,
        concepto, base_imponible, tipo_iva, cuota_iva, total, moneda,
        verifactu_hash_previo
    ) VALUES (
        p_booking_id, v_serie, v_numero, current_date,
        CASE WHEN p_receptor_nif IS NULL THEN 'simplificada' ELSE 'completa' END,
        p_receptor_nif,
        COALESCE(p_receptor_nombre, v_booking.guest_name),
        p_receptor_direccion,
        COALESCE(p_receptor_email, v_booking.guest_email),
        v_concepto, v_base, v_tipo_iva, v_cuota, v_total, 'EUR',
        v_hash_previo
    ) RETURNING id INTO v_invoice_id;

    -- Generar verifactu_hash con los campos clave (SHA256 hex)
    UPDATE public.invoices SET verifactu_hash = encode(
        digest(
            COALESCE(verifactu_hash_previo, '') || '|' ||
            emisor_nif || '|' || serie || '|' || numero::text || '|' ||
            fecha_emision::text || '|' || total::text || '|' || cuota_iva::text,
            'sha256'
        ), 'hex')
    WHERE id = v_invoice_id;

    RETURN QUERY SELECT v_invoice_id, v_serie, v_numero, v_total;
END $function$;

CREATE OR REPLACE FUNCTION public.submit_traveler_records(p_booking_code text, p_travelers jsonb)
 RETURNS TABLE(saved integer, booking_id bigint)
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_booking_id bigint;
    v_check_in date;
    v_check_out date;
    v_status text;
    v_count int := 0;
    v_traveler jsonb;
BEGIN
    -- Validar booking
    SELECT id, check_in, check_out, status
    INTO v_booking_id, v_check_in, v_check_out, v_status
    FROM public.guest_bookings
    WHERE booking_code = upper(p_booking_code);

    IF v_booking_id IS NULL THEN
        RAISE EXCEPTION 'booking_not_found' USING ERRCODE = '22023';
    END IF;
    IF v_status NOT IN ('confirmed', 'completed') THEN
        RAISE EXCEPTION 'booking_status_invalid: %', v_status USING ERRCODE = '22023';
    END IF;
    IF v_check_in - current_date > 7 THEN
        RAISE EXCEPTION 'precheckin_too_early' USING ERRCODE = '22023';
    END IF;
    IF v_check_out < current_date THEN
        RAISE EXCEPTION 'booking_already_past' USING ERRCODE = '22023';
    END IF;
    IF jsonb_array_length(p_travelers) = 0 OR jsonb_array_length(p_travelers) > 20 THEN
        RAISE EXCEPTION 'invalid_traveler_count' USING ERRCODE = '22023';
    END IF;

    DELETE FROM public.traveler_records WHERE traveler_records.booking_id = v_booking_id AND submitted_at IS NULL;

    FOR v_traveler IN SELECT * FROM jsonb_array_elements(p_travelers) LOOP
        INSERT INTO public.traveler_records (
            booking_id, is_titular,
            apellido_primero, apellido_segundo, nombre, sexo,
            tipo_documento, numero_documento, soporte_documento,
            nacionalidad, fecha_nacimiento,
            direccion_via, direccion_municipio, direccion_cp, direccion_pais,
            telefono_fijo, telefono_movil, email,
            parentesco, firma_base64
        ) VALUES (
            v_booking_id,
            COALESCE((v_traveler->>'is_titular')::boolean, false),
            v_traveler->>'apellido_primero',
            v_traveler->>'apellido_segundo',
            v_traveler->>'nombre',
            v_traveler->>'sexo',
            v_traveler->>'tipo_documento',
            v_traveler->>'numero_documento',
            v_traveler->>'soporte_documento',
            v_traveler->>'nacionalidad',
            (v_traveler->>'fecha_nacimiento')::date,
            v_traveler->>'direccion_via',
            v_traveler->>'direccion_municipio',
            v_traveler->>'direccion_cp',
            v_traveler->>'direccion_pais',
            v_traveler->>'telefono_fijo',
            v_traveler->>'telefono_movil',
            v_traveler->>'email',
            v_traveler->>'parentesco',
            v_traveler->>'firma_base64'
        );
        v_count := v_count + 1;
    END LOOP;

    RETURN QUERY SELECT v_count, v_booking_id;
END $function$;

CREATE OR REPLACE FUNCTION public.record_marketing_consent(p_email text, p_granted boolean, p_source text DEFAULT 'admin_panel'::text, p_ip text DEFAULT NULL::text, p_user_agent text DEFAULT NULL::text, p_legal_version text DEFAULT '1.0'::text, p_booking_code text DEFAULT NULL::text)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    log_id UUID;
    norm_email TEXT := LOWER(TRIM(p_email));
BEGIN
    INSERT INTO public.customers (email)
    VALUES (norm_email) ON CONFLICT (email) DO NOTHING;

    IF p_granted THEN
        UPDATE public.customers SET
            marketing_consent = true,
            marketing_consent_at = now(),
            marketing_consent_source = p_source,
            marketing_consent_revoked_at = NULL,
            updated_at = now()
        WHERE email = norm_email;
    ELSE
        UPDATE public.customers SET
            marketing_consent = false,
            marketing_consent_revoked_at = now(),
            updated_at = now()
        WHERE email = norm_email;
    END IF;

    INSERT INTO public.consent_log (customer_email, purpose, granted, source, ip, user_agent, legal_version, booking_code)
    VALUES (norm_email, 'marketing', p_granted, p_source, p_ip, p_user_agent, p_legal_version, p_booking_code)
    RETURNING id INTO log_id;

    RETURN log_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.search_kb_chunks(query_embedding vector, match_threshold double precision DEFAULT 0.25, match_count integer DEFAULT 6, lang text DEFAULT 'es'::text)
 RETURNS TABLE(id uuid, title text, content text, source_type text, metadata jsonb, similarity double precision)
 LANGUAGE plpgsql
 STABLE
AS $function$
BEGIN
    RETURN QUERY
    SELECT kc.id, kc.title, kc.content, kc.source_type, kc.metadata,
        1 - (kc.embedding <=> query_embedding) AS similarity
    FROM public.kb_chunks kc
    WHERE kc.embedding IS NOT NULL
      AND (lang IS NULL OR kc.language = lang)
      AND 1 - (kc.embedding <=> query_embedding) > match_threshold
    ORDER BY kc.embedding <=> query_embedding
    LIMIT match_count;
END $function$;

