CREATE OR REPLACE FUNCTION public.create_booking_hold(p_apartment_id bigint, p_check_in date, p_check_out date, p_pax integer, p_guest_name text, p_guest_email text, p_guest_phone text DEFAULT NULL::text)
 RETURNS TABLE(booking_id bigint, booking_code text, total_price numeric, expires_at timestamp with time zone)
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_total numeric;
    v_breakdown jsonb;
    v_code text;
    v_expires timestamptz := now() + interval '15 minutes';
    v_id bigint;
BEGIN
    SELECT ca.total_price, ca.price_breakdown INTO v_total, v_breakdown
    FROM public.check_availability(p_check_in, p_check_out, p_pax) ca
    WHERE ca.apartment_id = p_apartment_id
    LIMIT 1;

    IF v_total IS NULL THEN
        RAISE EXCEPTION 'apartment_not_available' USING ERRCODE = '22023';
    END IF;

    LOOP
        v_code := public.generate_booking_code();
        EXIT WHEN NOT EXISTS (SELECT 1 FROM public.guest_bookings gb WHERE gb.booking_code = v_code);
    END LOOP;

    INSERT INTO public.guest_bookings (
        apartment_id, guest_name, guest_email, guest_phone,
        pax_count, check_in, check_out, total_price, price_breakdown,
        status, expires_at, booking_code, source
    ) VALUES (
        p_apartment_id, p_guest_name, p_guest_email, p_guest_phone,
        p_pax, p_check_in, p_check_out, v_total, v_breakdown,
        'hold', v_expires, v_code, 'web'
    )
    RETURNING id INTO v_id;

    RETURN QUERY SELECT v_id, v_code, v_total, v_expires;
END $function$;

